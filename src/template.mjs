// Утверждённый текст напоминания. Менять формулировки нельзя —
// только подставлять имя клиента и день/время тренировки.
export function buildReminderMessage(name, whenText) {
  return `Здравствуйте, ${name}! 🙌
Перед тренировкой желательно немного разогреться, чтобы не тратить время занятия на разминку.

Рекомендуем:
- 10 минут лёгкой пробежки
- 5 минут скакалки
- 5 минут растяжки

Если не получится сделать заранее — ничего страшного, всё это можно будет выполнить на тренировке с Виктором.

Ждём вас ${whenText}!`;
}
